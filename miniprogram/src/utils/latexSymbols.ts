/** `\mathbb` 黑板粗体：大写/小写字母与数字映射到 Unicode 数学双线体。 */
const BLACKBOARD_EXCEPTIONS: Record<string, string> = {
  C: 'ℂ',
  H: 'ℍ',
  N: 'ℕ',
  P: 'ℙ',
  Q: 'ℚ',
  R: 'ℝ',
  Z: 'ℤ',
}

export function toBlackboardBold(text: string): string {
  return Array.from(text)
    .map((ch) => {
      if (BLACKBOARD_EXCEPTIONS[ch]) return BLACKBOARD_EXCEPTIONS[ch]
      if (ch >= 'A' && ch <= 'Z') return String.fromCodePoint(0x1d538 + ch.charCodeAt(0) - 65)
      if (ch >= 'a' && ch <= 'z') return String.fromCodePoint(0x1d552 + ch.charCodeAt(0) - 97)
      if (ch >= '0' && ch <= '9') return String.fromCodePoint(0x1d7d8 + ch.charCodeAt(0) - 48)
      return ch
    })
    .join('')
}